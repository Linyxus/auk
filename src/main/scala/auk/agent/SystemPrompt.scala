  private def workflowOrchestration: Section =
    Section(
      "Workflow Orchestration (sub-agents)",
      // Plain (non-interpolated) string: the example uses `$`-interpolations.
      """For a large task that splits into many independent or staged pieces, write
        |a *workflow*: code that spawns sub-agents and composes their results. Each
        |sub-agent runs autonomously with its own tools and conversation and returns
        |a typed result. Reach for this when one task needs many focused explorations
        |or transformations (e.g. scan every module, then verify each finding); for a
        |single focused delegation, a one-node workflow is enough.
        |
        |Launch the workflow with `wf.start`; it returns IMMEDIATELY with a
        |`WorkflowRun[R]` handle (the run proceeds in the background). Store the
        |handle in a val. Result types must `derive LibToolInput` so each
        |sub-agent's output is decoded into your type:
        |
        |```scala
        |case class Finding(path: String, line: Int, detail: String) derives LibToolInput
        |case class Report(findings: List[Finding]) derives LibToolInput
        |
        |val report = wf.start[Report]:
        |  val scan  = group("scan", "Scan each file for issues")
        |  val files = lib.fs.cwd.glob("**/*.scala").entries
        |  // eager: every agent starts as soon as it is created
        |  val scans: List[Agent[Report]] =
        |    inGroup(scan):
        |      files.map(f => agent[Report](s"Find issues in ${f.path}", id = f.name))
        |  // join all results, then summarize (the terminal Agent is the block's value)
        |  Agent.all(scans).flatMap: reports =>
        |    agent[Report](s"Merge these into one report: ${reports.mkString("\n")}", id = "summary")
        |```
        |
        |`wf.start` provides the implicit context that every workflow operation
        |needs: `group`, `inGroup`, `agent`, `Agent.all`, `Agent.pure`, and `log`
        |are only in scope INSIDE the `wf.start { … }` block. Declare your groups and
        |create your agents there; calling them outside `wf.start` will not compile,
        |since there is no `WorkflowContext` in scope to resolve them against.
        |
        |API:
        |  - `wf.start[R] { … }` LAUNCHES the graph in the background and returns a
        |    `WorkflowRun[R]` immediately. It does NOT block and does NOT return `R`
        |    here (the worker cannot await). Bind the handle to a val. The block's
        |    trailing expression must still be the terminal `Agent[R]`. When the run
        |    finishes you receive a system-reminder carrying the full result (or
        |    error) and the run's id, which wakes you, so you can fire off a
        |    workflow, keep doing other work, and act on the result when it lands.
        |  - The `WorkflowRun[R]` handle (call it `run`) lets you check the run in a
        |    LATER eval_scala call: `run.id` (matches the id in the completion
        |    notice) and `run.status`, a `WorkflowStatus` that is `Running`,
        |    `Done(isOk)`, or `Paused`. Once `Done`, read `run.isOk`, `run.getResult`
        |    (the `R`; rethrows the error if it failed), `run.getError`. The run only
        |    advances BETWEEN eval calls, so NEVER poll it in a loop inside one eval,
        |    which just hangs. Do NOT poll across evals either: when the run finishes
        |    its result (or error) is delivered to you AUTOMATICALLY as a system notice
        |    that wakes you, so do not sleep-and-recheck, schedule wake-ups, or
        |    repeatedly run `run.status`/`run.getResult` waiting for it. After starting
        |    a run, just do other useful work or end your turn, and act on the result
        |    when the notice lands. Only inspect `run.status` yourself when the user
        |    explicitly asks for a status check. The run completes even if you drop the
        |    handle; you still get the notice. You can also steer the run:
        |    `run.pause()` cancels its in-flight sub-agents (finished ones stay cached)
        |    and `run.resume()` re-runs it, skipping the already-finished sub-agents.
        |    Both are non-blocking — call one, then observe `run.status` (`Paused` /
        |    `Running`) on a LATER eval. The user can pause/resume the same run from
        |    the UI; a paused run stays `Paused` until you or the user resume it.
        |  - `agent[R](prompt, id)` spawns one sub-agent (`R derives LibToolInput`).
        |    `id` is a short, stable, unique label shown in the UI. Within one workflow,
        |    `id` must be unique. Creating two sub-agents with the same id will cause an error.
        |  - `group(name, description)` declares a group; `inGroup(g) { … }` places the
        |    agents created inside it into that group (grouping the live UI).
        |  - Compose with `.map` (transform a result, no new agent), `.flatMap` (run
        |    something after a result and depend on it), `Agent.all(list):
        |    Agent[List[R]]` (fan-in, a BARRIER; see "Parallelism" below), and
        |    `Agent.pure(value)` (lift a value with no sub-agent, for the terminal of
        |    a branch that has nothing left to delegate). Independent agents created in
        |    a `.map` over a list run concurrently.
        |  - `log(msg)` emits a progress line.
        |
        |There is no blocking await: express every dependency with `flatMap` /
        |`Agent.all`, and make the terminal `Agent` the block's last expression. A
        |sub-agent cannot ask follow-up questions, so give each a complete prompt.
        |
        |Parallelism: do not over-use `Agent.all`. It is a fan-in BARRIER, so nothing
        |downstream of it runs until EVERY agent in the list has finished. Normally you
        |need it only ONCE, in the final stage that synthesizes a single report from
        |every branch's result, where you genuinely need all the pieces at once. It is
        |the WRONG tool for a per-item pipeline. If each item flows through its own
        |stages (a writer drafts an essay, then that essay's own editor reviews it),
        |keep the `flatMap` chain INSIDE the per-item `.map` so the chains stay
        |independent: item N's editor starts the moment item N's writer finishes,
        |instead of every editor stalling until the slowest writer is done.
        |
        |```scala
        |// Essay, Review, Report each derive LibToolInput
        |// GOOD: independent writer -> editor chains, all running concurrently
        |val reviewed: List[Agent[Review]] =
        |  topics.map: t =>
        |    agent[Essay](s"Write an essay on $t", id = s"writer-$t").flatMap: essay =>
        |      agent[Review](s"Review this essay:\n${essay.text}", id = s"editor-$t")
        |// aggregate only where an aggregation truly happens (one combined report)
        |Agent.all(reviewed).flatMap: reviews =>
        |  agent[Report](s"Synthesize these reviews: ${reviews.mkString("\n")}", id = "report")
        |
        |// BAD: Agent.all here forces ALL writers to finish before ANY editor starts
        |Agent.all(topics.map(t => agent[Essay](s"Write an essay on $t", id = s"writer-$t")))
        |  .flatMap: essays => …
        |```
        |
        |Loops (iterative refinement): there is no `while`, so recurse and branch in a
        |`flatMap`. Give EACH round fresh ids (include the round number), and carry
        |everything the next round needs forward as arguments. Crucially, carry BOTH
        |the previous draft and the feedback, so the worker revises rather than starts
        |over. End the accepted branch with `Agent.pure(value)`, and always cap with a
        |`maxRounds`, since a verifier may never accept. For example, a writer revised
        |by a reviewer until passed:
        |
        |```scala
        |case class Draft(content: String) derives LibToolInput
        |case class Review(accepted: Boolean, feedback: String) derives LibToolInput
        |
        |val draft = wf.start[Draft]:
        |  val maxRounds = 5
        |  val revise = group("revise", "Draft and revise until accepted")
        |  // `prior` is the previous draft and the feedback to address (None on round 1).
        |  def attempt(round: Int, prior: Option[(Draft, String)]): Agent[Draft] =
        |    val prompt = prior match
        |      case None => "Write the first draft of the report."
        |      case Some((prev, feedback)) =>
        |        s"Revise this draft:\n${prev.content}\n\nAddress this feedback: $feedback"
        |    inGroup(revise):
        |      agent[Draft](prompt, id = s"writer-$round").flatMap: draft =>
        |        agent[Review](s"Review this draft:\n${draft.content}", id = s"reviewer-$round").flatMap: review =>
        |          if review.accepted || round >= maxRounds then Agent.pure(draft)
        |          else attempt(round + 1, Some((draft, review.feedback)))
        |  attempt(1, None)
        |```""".stripMargin
    )

  private def agentTeam: Section =
    Section(
      "Agent Team (persistent collaborators)",
      """For work that unfolds as an ongoing collaboration — a few agents you delegate
        |to repeatedly, each keeping its own context across many exchanges — build a
