package auk.agent

import gears.async.Async
import auk.generated.LibrarySource
import auk.runtime.repl.ReplPreamble

/** Composes the system prompt for the top-level interactive agent.
  *
  * The prompt has two parts, assembled into one stream of `##` markdown
  * sections:
  *
  *   - a **static** part: the identity and the fixed instruction sections
  *     ([[staticSections]]) that are the same every run; and
  *   - a **dynamic** part: [[dynamicSections]] whose bodies are gathered from
  *     the live session ([[PromptEnv]]) at start-up: the environment (working
  *     directory, model, git status) and any project-wide instructions
  *     (CLAUDE.md / AGENTS.md).
  *
  * New concerns slot in as another [[Section]] or [[DynamicSection]] without
  * touching the callers. The two static pieces that must never drift from the
  * code are pulled from their single sources of truth: the runtime library
  * interface is the embedded text of AukInterface.scala
  * ([[auk.generated.LibrarySource]], generated by build.sbt), and the session
  * preamble is the exact string [[auk.runtime.repl.ScalaRepl]] evaluates at
  * session start ([[ReplPreamble.Source]]).
  *
  * This object is the single home for every agent's system prompt: the top-level
  * interactive agent ([[default]] / [[build]]), a workflow's typed worker
  * sub-agents ([[workflowAgent]]), and a persistent team member ([[teamMember]]).
  * They all drive the same eval_scala action surface, so they share one
  * [[scalaEvaluation]] section and differ only in identity and in how they finish:
  * the interactive agent keeps the conversation going, a workflow sub-agent returns
  * a typed value through `submit_result`, and a team member finishes a turn (going
  * idle) or messages its teammates.
  */
object SystemPrompt:

  /** One titled block of the prompt, rendered as a `##` markdown section. */
  final case class Section(title: String, body: String)

  val Identity: String =
    "You are auk, an interactive coding agent running in the user's terminal. " +
      "You help with software engineering tasks using the tools available to " +
      "you: reading and changing code, running commands, and answering " +
      "questions about the project. Be direct and concise, and prefer acting " +
      "over describing what you would do."

  /** The fixed instruction sections, identical every run. [[mcpSetup]] comes last
    * so it sits next to the conditional [[mcpTools]] section in [[build]]. */
  def staticSections: List[Section] =
    List(scalaEvaluation, userCommunication, projectMemory, workflowOrchestration, agentTeam, mcpSetup)

  /** The environment-derived sections, in render order. */
  def dynamicSections: List[DynamicSection] =
    List(DynamicSection.ProjectInfo, DynamicSection.ProjectInstructions, DynamicSection.MemoryIndex)

  /** The static-only prompt: identity plus [[staticSections]], no environment
    * I/O. The safe default for headless/test callers and the [[Engine]]'s
    * fallback. */
  def default: String = render(Identity, staticSections)

  /** The full prompt for a live session: the static prompt, the MCP *tools*
    * section when MCP servers are configured, any caller-supplied extra sections
    * (e.g. the live skill index, whose body is state gathered at startup), then
    * every dynamic section that has something to contribute for `env`. How to
    * CONFIGURE a server is always present, in [[staticSections]]. */
  def build(
      env: PromptEnv,
      mcpConfigured: Boolean = false,
      extraSections: List[Section] = Nil
  )(using Async): String =
    val dyn = dynamicSections.flatMap(d => d.render(env).map(Section(d.title, _)))
    render(Identity, staticSections ++ mcpSections(mcpConfigured) ++ extraSections ++ dyn)

  /** The MCP *tools* section, included only when MCP servers are configured.
    * Shared by every agent's prompt — main, workflow sub-agent, team member —
    * since they all receive the MCP tools when servers are configured. The
    * companion [[mcpSetup]] section is NOT here: editing `.auk/config` is the
    * interactive agent's concern, so it rides in [[staticSections]] instead. */
  private def mcpSections(mcpConfigured: Boolean): List[Section] =
    if mcpConfigured then List(mcpTools) else Nil

  def render(identity: String, sections: List[Section]): String =
    (identity :: sections.map(s => s"## ${s.title}\n\n${s.body}")).mkString("\n\n")

  // -- sub-agent prompts (autonomous workers) ---------------------------------

  /** Identity for a workflow's worker sub-agent (spawned by `agent[R](…)`). */
  val WorkflowAgentIdentity: String =
    "You are a worker sub-agent inside a larger automated workflow. You have been " +
      "given one focused task to carry out on your own. You run autonomously, with " +
      "no human to talk to and no way to ask follow-up questions, so make " +
      "reasonable assumptions when details are missing and take the task all the way " +
      "to completion. Other agents may depend on your answer, so be accurate and " +
      "thorough; the structured result you submit is the only thing the workflow sees."

  /** A workflow worker sub-agent's prompt: act through eval_scala, then return a
    * typed value through the injected `submit_result` tool. Includes the MCP
    * tools section when servers are configured, since the sub-agent gets those
    * tools — but never [[mcpSetup]]: it does not configure the project. */
  def workflowAgent(mcpConfigured: Boolean = false): String =
    render(WorkflowAgentIdentity, List(scalaEvaluation, typedResult) ++ mcpSections(mcpConfigured))

  /** A team member's prompt: an identity naming the member and its role, the shared
    * eval_scala surface, and how to collaborate over asynchronous team messages. Used
    * by the host `TeamBridge` as its `memberPrompt`. Includes the MCP tools section
    * when servers are configured, since a member gets those tools — but never
    * [[mcpSetup]]: it does not configure the project. */
  def teamMember(id: String, description: String, mcpConfigured: Boolean = false): String =
    render(teamMemberIdentity(id, description), List(scalaEvaluation, teamMemberWork) ++ mcpSections(mcpConfigured))

  private def teamMemberIdentity(id: String, description: String): String =
    s"You are '$id', a member of an agent team: a persistent collaborator working " +
      "under a lead agent (the main agent), alongside any other members. Your role is " +
      s"$description. You run autonomously through eval_scala, with no human to talk to " +
      "directly. Unlike a one-shot worker you are long-lived — you keep your context " +
      "across many exchanges with the lead and other members — so treat this as an " +
      "ongoing collaboration, and be accurate and thorough: the messages you send are " +
      "all your teammates see of your work."

